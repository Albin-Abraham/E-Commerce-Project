interface TokenNode {
  $value?: string;
  $type?: string;
  $description?: string;
  [key: string]: any;
}

/**
 * Deep merge utility for objects
 */
function deepMerge(target: any, source: any): any {
  const output = { ...target };
  if (isObject(target) && isObject(source)) {
    Object.keys(source).forEach((key) => {
      if (isObject(source[key])) {
        if (!(key in target)) {
          Object.assign(output, { [key]: source[key] });
        } else {
          output[key] = deepMerge(target[key], source[key]);
        }
      } else {
        Object.assign(output, { [key]: source[key] });
      }
    });
  }
  return output;
}

function isObject(item: any): boolean {
  return item && typeof item === "object" && !Array.isArray(item);
}

/**
 * Recursively load all JSON token files from a directory
 */
function loadTokens(dir: string): Record<string, any> {
  let result: Record<string, any> = {};
  if (!fs.existsSync(dir)) return result;

  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      result = deepMerge(result, loadTokens(fullPath));
    } else if (entry.name.endsWith(".json")) {
      const content = JSON.parse(fs.readFileSync(fullPath, "utf-8"));
      result = deepMerge(result, content);
    }
  }
  return result;
}

/**
 * Resolve alias references like {primitives.color.neutral.100}
 */
function resolveAliases(tree: Record<string, any>): Record<string, any> {
  const getValueByPath = (obj: any, pathStr: string, visited = new Set<string>()): string | undefined => {
    if (visited.has(pathStr)) {
      console.warn(`[WARN] Circular alias detected: ${pathStr}`);
      return undefined;
    }
    visited.add(pathStr);

    const parts = pathStr.split(".");
    let curr = obj;
    for (const part of parts) {
      if (!curr) return undefined;
      curr = curr[part];
    }
    const val = curr?.$value ?? (typeof curr === "string" ? curr : undefined);
    if (typeof val === "string") {
      const aliasMatch = val.match(/^{(.+)}$/);
      if (aliasMatch) {
        return getValueByPath(obj, aliasMatch[1], visited);
      }
    }
    return val;
  };

  const traverse = (node: any): any => {
    if (!isObject(node)) return node;
    const output: Record<string, any> = {};
    for (const key of Object.keys(node)) {
      if (key === "$value" && typeof node.$value === "string") {
        const aliasMatch = node.$value.match(/^{(.+)}$/);
        if (aliasMatch) {
          const resolved = getValueByPath(tree, aliasMatch[1]);
          output.$value = resolved !== undefined ? resolved : node.$value;
        } else {
          output.$value = node.$value;
        }
      } else {
        output[key] = traverse(node[key]);
      }
    }
    return output;
  };

  return traverse(tree);
}

