import { describe, expect, it } from "vitest";

import {
  buildLoginSchema,
  buildSignupSchema,
} from "../../../shell/pages/static-pages/configs/auth-schema";
import { buildBranchSchema } from "../../../shell/pages/static-pages/configs/branch-schema";
import { FieldRegistry } from "@form-core/modules/field-registry";
import { SchemaNormalizer } from "../../ui/form/utils/SchemaNormalizer";

describe("Production Form Schemas Architectural Validation", () => {
  const schemas = [
    { name: "Branch Schema", factory: buildBranchSchema },
    { name: "Auth Login Schema", factory: buildLoginSchema },
    { name: "Auth Signup Schema", factory: buildSignupSchema },
  ];

  schemas.forEach(({ name, factory }) => {
    describe(`${name}`, () => {
      it("should be successfully generated by the schema factory", () => {
        const schema = factory();
        expect(schema).toBeDefined();
        expect(schema.id).toBeDefined();
      });

      it("should pass SchemaNormalizer to build a valid UI Tree", () => {
        const schema = factory();
        const uiTree = SchemaNormalizer.normalize(schema as any);

        expect(Array.isArray(uiTree)).toBe(true);
        expect(uiTree.length).toBeGreaterThan(0);

        // Ensure all UI nodes have deterministic bindings for testing (data-field-id)
        const validateIds = (nodes: any[]) => {
          nodes.forEach((node) => {
            expect(node.id).toBeDefined();
            if (node.fields) validateIds(node.fields);
          });
        };
        validateIds(uiTree);
      });

      it("should construct a flat FieldRegistry without circular dependencies", () => {
        const schema = factory();

        // FieldRegistry construction automatically runs `normalizeFormDefinition`
        // which runs dependency cycle detection via DFS.
        // If there is a cycle in conditional logic or reactive expressions, it will throw an Error.
        expect(() => {
          const registry = new FieldRegistry(schema as any);

          // Basic validations on the normalized map
          expect(registry.definition).toBeDefined();
          expect(
            Object.keys(registry.definition.fields).length
          ).toBeGreaterThan(0);
          expect(
            Object.keys(registry.definition.sections).length
          ).toBeGreaterThan(0);
        }).not.toThrow();
      });
    });
  });
});
