import { useCallback } from "react";

import { useForm } from "../hooks/useForm";
import type { FormDefinition } from "../types";

/**
 * React Hook Form (RHF) Style Adapter for the Custom FormCore
 *
 * This adapter bridges the gap between the high-performance atomic
 * state engine and the familiar developer experience of React Hook Form.
 *
 * Usage:
 * const { register, formState: { errors }, handleSubmit } = useFormAdapter(mySchema);
 * <input {...register('firstName')} />
 */
export function useFormAdapter<T extends Record<string, any>>(
  definition: FormDefinition,
  initialData?: Partial<T>
) {
  // 1. Initialize the custom core engine
  const {
    form,
    values,
    validity,
    isDirty,
    isValid,
    submit,
    getComponentProps,
  } = useForm<T>(definition, initialData);

  // 2. The Register Function (Mimics RHF register)
  // This binds standard React inputs to the high-performance external store
  const register = useCallback(
    (fieldId: string) => {
      // We fetch the core component props generated by the engine
      const coreProps = getComponentProps(fieldId);
      const inputProps: any = coreProps.inputProps;

      return {
        name: fieldId,
        id: fieldId,
        // Connect to the engine's onChange handler (which updates the external store without re-rendering)
        onChange: (
          e: React.ChangeEvent<
            HTMLInputElement | HTMLSelectElement | HTMLTextAreaElement
          >
        ) => {
          inputProps.onChange?.(e.target.value);
        },
        // Connect to the engine's blur for validation triggers
        onBlur: () => {
          form.setTouched(fieldId);
          inputProps.onBlur?.();
        },
        // Ref forwarding is critical for RHF-style adapters.
        // This allows the parent to manage focus on error, or imperatively
        // call handlers on complex UI primitives (like resetting a TreeSelect).
        ref: (element: any) => {
          // If your custom engine tracks element refs for focus management (e.g. focusFirstError),
          // you register the DOM element here.
          const coreRef = (coreProps as any).ref;
          if (typeof coreRef === "function") {
            coreRef(element);
          } else if (coreRef) {
            coreRef.current = element;
          }
        },
        // The current value, though in a real scenario you'd want to use useFieldAtom
        // inside a wrapper component to ensure true atomic re-renders.
        // For standard RHF usage, this provides the snapshot value.
        value: values[fieldId] ?? "",
      };
    },
    [form, values, getComponentProps]
  );

  // 3. Map to RHF standard API surface
  return {
    register,
    handleSubmit:
      (onValid?: (data: T) => void) => async (e?: React.BaseSyntheticEvent) => {
        e?.preventDefault();
        const success = await submit();
        if (success && onValid) {
          onValid(form.values);
        }
      },
    formState: {
      errors: validity, // Maps your internal validity structure to 'errors'
      isDirty,
      isValid,
      values,
    },
    // Expose the raw engine for advanced use cases
    engine: form,
  };
}
